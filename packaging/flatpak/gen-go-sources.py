#!/usr/bin/env python3
"""Writes go-modules.yml: flatpak-builder sources that recreate vendor/ offline.

Flathub builds without network access, so every Go module the build needs is
listed as an archive from proxy.golang.org (with its sha256), unpacked into
vendor/<module path>, plus vendor/modules.txt, which `go build -mod=vendor`
checks against go.mod. Run from anywhere after changing go.mod/go.sum:

    packaging/flatpak/gen-go-sources.py
"""

import hashlib
import json
import pathlib
import subprocess
import tempfile
import urllib.request

root = pathlib.Path(__file__).resolve().parents[2]
out = pathlib.Path(__file__).resolve().parent / "flathub" / "go-modules.yml"


def escape(path):
    # The module proxy spells uppercase letters as "!" + lowercase.
    return "".join("!" + c.lower() if c.isupper() else c for c in path)


with tempfile.TemporaryDirectory() as tmp:
    vendor = pathlib.Path(tmp) / "vendor"
    subprocess.run(["go", "mod", "vendor", "-o", str(vendor)], cwd=root, check=True)
    modules_txt = (vendor / "modules.txt").read_text()

sources = []
for line in modules_txt.splitlines():
    parts = line.split()
    if len(parts) != 3 or parts[0] != "#":
        continue  # package lines, "## explicit" markers, replacements
    path, version = parts[1], parts[2]
    url = f"https://proxy.golang.org/{escape(path)}/@v/{escape(version)}.zip"
    with urllib.request.urlopen(url) as resp:
        sha256 = hashlib.sha256(resp.read()).hexdigest()
    sources.append({
        "type": "archive",
        "archive-type": "zip",
        "url": url,
        "sha256": sha256,
        "dest": f"vendor/{path}",
        # Zip entries start with "<module path>@<version>/".
        "strip-components": path.count("/") + 1,
    })
sources.append({
    "type": "inline",
    "contents": modules_txt,
    "dest": "vendor",
    "dest-filename": "modules.txt",
})

out.parent.mkdir(exist_ok=True)
# JSON is valid YAML; flatpak-builder reads either.
out.write_text("# Generated by packaging/flatpak/gen-go-sources.py; do not edit.\n"
               + json.dumps(sources, indent=2) + "\n")
print(f"{out.relative_to(root)}: {len(sources) - 1} modules")
